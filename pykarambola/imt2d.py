def _validate_max_s(max_s):
    if isinstance(max_s, bool) or not isinstance(max_s, (int, np.integer)):
        raise ValueError(f"max_s must be a non-negative integer, got {max_s!r}")  # noqa: TRY004
    max_s = int(max_s)
    if max_s < 0:
        raise ValueError(f"max_s must be >= 0, got {max_s}")
    return max_s


def _validate_s_order(s):
    if isinstance(s, bool) or not isinstance(s, (int, np.integer)):
        raise ValueError(f"s must be a non-negative integer, got {s!r}")  # noqa: TRY004
    s = int(s)
    if s < 0:
        raise ValueError(f"s must be >= 0, got {s}")
    return s


def _parse_spacing(spacing, xy_order):
    """Return physical pixel sizes (dx, dy) in internal Cartesian (x, y) order."""
    if isinstance(spacing, bool):
        raise ValueError(f"spacing values must be positive finite numbers, got {spacing!r}")
    if np.ndim(spacing) == 0:
        s0 = s1 = float(spacing)
    else:
        sp_raw = np.asarray(spacing)
        if sp_raw.dtype == np.bool_:
            raise ValueError(f"spacing values must be positive finite numbers, got {spacing!r}")
        sp = np.asarray(sp_raw, dtype=np.float64)
        if sp.ndim != 1 or sp.size != 2:
            raise ValueError(
                f"spacing must be a scalar or 2-element sequence, got shape {sp.shape}"
            )
        s0, s1 = float(sp[0]), float(sp[1])
    if not (np.isfinite(s0) and np.isfinite(s1) and s0 > 0.0 and s1 > 0.0):
        raise ValueError(f"spacing values must be positive finite numbers, got {(s0, s1)}")
    # When xy_order=True:  axis 0 is x, axis 1 is y -> (dx, dy) = (s0, s1)
    # When xy_order=False: axis 0 is y (row), axis 1 is x (col) -> (dx, dy) = (s1, s0)
    return (s0, s1) if xy_order else (s1, s0)


def _parse_thresholds(threshold):
    """Return (thresholds_1d_float64, is_scalar)."""
    try:
        arr = np.asarray(threshold, dtype=np.float64)
    except (TypeError, ValueError) as exc:
        raise ValueError(f"cannot convert threshold to float64: {threshold!r}") from exc
    if arr.ndim == 0:
        val = float(arr)
        if not np.isfinite(val):
            raise ValueError(f"threshold must be finite, got {val!r}")
        return np.array([val], dtype=np.float64), True
    if arr.ndim == 1:
        if arr.size > 0 and not np.all(np.isfinite(arr)):
            raise ValueError("threshold values must all be finite")
        return arr, False
    raise ValueError(
        f"threshold must be a scalar or 1D sequence, got {arr.ndim}D array"
    )


def _parse_flags(method, analyze, connect):
    if method not in ('interpolated', 'regular'):
        raise ValueError(f"method must be 'interpolated' or 'regular', got {method!r}")
    if analyze not in ('white', 'black'):
        raise ValueError(f"analyze must be 'white' or 'black', got {analyze!r}")
    if connect not in ('white', 'black'):
        raise ValueError(f"connect must be 'white' or 'black', got {connect!r}")
    return method == 'regular', analyze == 'black', connect == 'black'


def _prepare_image_xy(image, boundary, xy_order):
    """Validate 2D image, convert to float64 in (x, y) order, and apply boundary padding."""
    arr = np.asarray(image, dtype=np.float64)
    if arr.ndim != 2:
        raise ValueError(f"image must be 2D, got {arr.ndim}D array with shape {arr.shape}")
    if arr.size > 0 and not np.all(np.isfinite(arr)):
        raise ValueError("image must contain only finite values")

    # Convert to internal Cartesian (x, y) array ordering
    arr_xy = arr if xy_order else arr.T

    if boundary is None:
        return arr_xy
    if isinstance(boundary, str):
        if boundary != 'periodic':
            raise ValueError(
                f"boundary must be a float, 'periodic', or None; got {boundary!r}"
            )
        if arr_xy.size == 0:
            return arr_xy
        # Append 1 wrapped column/row on the high side -> exactly W x H unique 2x2 cells,
        # matching papaya2's periodic Minkowski map indexing without seam double-counting.
        return np.pad(arr_xy, ((0, 1), (0, 1)), mode='wrap')

    # Constant padding value
    if isinstance(boundary, bool):
        pad_val = float(boundary)
    else:
        try:
            pad_arr = np.asarray(boundary, dtype=np.float64)
        except (TypeError, ValueError) as exc:
            raise ValueError(
                f"boundary must be a float, 'periodic', or None; got {boundary!r}"
            ) from exc
        if pad_arr.ndim != 0:
            raise ValueError(
                "constant boundary must be a scalar float, got "
                f"shape {pad_arr.shape}"
            )
        pad_val = float(pad_arr)
    if not np.isfinite(pad_val):
        raise ValueError(f"constant boundary must be finite, got {pad_val!r}")
    if arr_xy.size == 0:
        return arr_xy
    return np.pad(arr_xy, ((1, 1), (1, 1)), mode='constant', constant_values=pad_val)


def _finalize_single_result(area, perimeter, psi):
    """Build standard single-object IMT result dict from (area, perimeter, psi)."""
    max_s = psi.size - 1
    area = float(area)
    perimeter = float(perimeter)
    if perimeter > 0.0:
        q = np.abs(psi) / perimeter
        q[0] = 1.0
        isoper = float(4.0 * np.pi * area / (perimeter * perimeter))
        beta102 = float((1.0 - q[2]) / (1.0 + q[2])) if max_s >= 2 else float('nan')
    else:
        q = np.full(max_s + 1, np.nan, dtype=np.float64)
        isoper = float('nan')
        beta102 = float('nan')
    return {
        'area': area,
        'perimeter': perimeter,
        'beta102': beta102,
        'isoper': isoper,
        'psi': psi,
        'q': q,
    }


def _accumulate_segments_psi(seg_dx, seg_dy, max_s):
    """Accumulate perimeter and psi[0..max_s] from oriented segment vectors (dx, dy)."""
    psi = np.zeros(max_s + 1, dtype=np.complex128)
    if seg_dx.size == 0:
        return 0.0, psi

    p = np.hypot(seg_dx, seg_dy)
    nz = p > 0.0
    if not np.any(nz):
        return 0.0, psi

    p_nz = p[nz]
    perimeter = float(np.sum(p_nz))
    psi[0] = perimeter
    if max_s >= 1:
        # Outward unit normal n = (dy/p) - i*(dx/p)
        n = (seg_dy[nz] - 1j * seg_dx[nz]) / p_nz
        cur = p_nz * n
        psi[1] = np.sum(cur)
        for s in range(2, max_s + 1):
            cur *= n
            psi[s] = np.sum(cur)
    return perimeter, psi


def _segment_psi_s(seg_dx, seg_dy, s):
    """Return per-segment contribution p * n^s (complex128, same length as seg_dx)."""
    out = np.zeros(seg_dx.size, dtype=np.complex128)
    if seg_dx.size == 0:
        return out
    p = np.hypot(seg_dx, seg_dy)
    nz = p > 0.0
    if not np.any(nz):
        return out
    p_nz = p[nz]
    if s == 0:
        out[nz] = p_nz
    else:
        n = (seg_dy[nz] - 1j * seg_dx[nz]) / p_nz
        out[nz] = p_nz * (n ** s)
    return out


