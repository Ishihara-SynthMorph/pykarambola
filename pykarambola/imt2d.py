"""
2D Irreducible Minkowski Tensors (IMTs), vectorized 2D marching squares,
Minkowski maps, Voronoi point-pattern morphometry, and 2D label-image analysis.

Ported from Papaya2 (Schaller, Wagner, & Kapfer, *Journal of Open Source
Software*, 5(54), 2538, 2020; https://github.com/morphometry/papaya2).

Mathematical definitions
------------------------
For a 2D body :math:`K` with piecewise-linear counterclockwise (CCW) boundary
:math:`\\partial K`, each oriented edge :math:`\\Delta = (\\Delta x, \\Delta y)`
of length :math:`p = \\|\\Delta\\|` has outward unit normal

.. math::

    \\mathbf{n} = (n_x, n_y) = \\left(\\frac{\\Delta y}{p}, -\\frac{\\Delta x}{p}\\right),
    \\qquad n = n_x + i n_y = e^{i \\phi_n}.

The Irreducible Minkowski Tensors (complex angular Fourier moments of the
boundary normal distribution) of order :math:`s \\ge 0` are

.. math::

    \\psi_s = \\oint_{\\partial K} e^{i s \\phi_n}\\, dl
            = \\sum_{e} p_e\\, n_e^s,

with normalized rotation-invariant magnitudes (Minkowski structure metrics)

.. math::

    q_s = \\frac{|\\psi_s|}{P}, \\qquad P = \\psi_0 = \\sum_e p_e,

anisotropy index :math:`\\beta_1^{0,2} = (1 - q_2) / (1 + q_2)`, and
isoperimetric ratio :math:`4 \\pi A / P^2`.

Axis conventions for images
---------------------------
By default (``xy_order=False``), image arrays follow the standard NumPy /
bioimage convention ``image[row, col]`` with shape ``(ny, nx)`` and
``spacing=(sy, sx)``. Coordinates are mapped as ``(x, y) = (col * sx, row * sy)``,
so outward normal angles are measured as ``atan2(n_row, n_col)`` (counterclockwise
in ``(col, row)`` space, i.e. clockwise on screen when row 0 is displayed at the
top). All rotation-invariant quantities (``area``, ``perimeter``, ``q``,
``beta102``, ``isoper``) are unaffected by axis orientation; flipping rows
complex-conjugates ``psi``.

Pass ``xy_order=True`` for bit-exact coordinate and phase compatibility with
Papaya2's Cartesian ``image[x, y]`` convention of shape ``(nx, ny)`` and
``spacing=(sx, sy)``.
"""

