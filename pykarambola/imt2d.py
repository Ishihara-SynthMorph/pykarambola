def _marching_squares_boundary_data(arr_xy, threshold, is_regular, analyze_black, connect_black):
    """Extract boundary cell LUT indices, edge interpolants, and cell geometry.

    Returns
    -------
    None if grid has no 2x2 neighborhoods or no boundary cells, along with bulk_area_cells.
    """
    nx, ny = arr_xy.shape
    if nx < 2 or ny < 2:
        return None

    if is_regular:
        work = (arr_xy >= threshold).astype(np.float64)
        eff_thr = 0.5
    else:
        work = arr_xy
        eff_thr = float(threshold)

    ll = work[:-1, :-1]
    ul = work[:-1, 1:]
    lr = work[1:, :-1]
    ur = work[1:, 1:]

    if analyze_black:
        lut = (
            (ll < eff_thr).astype(np.uint8)
            | ((ul < eff_thr).astype(np.uint8) << 1)
            | ((lr < eff_thr).astype(np.uint8) << 2)
            | ((ur < eff_thr).astype(np.uint8) << 3)
        )
        disconnect_fg = not connect_black
    else:
        lut = (
            (ll >= eff_thr).astype(np.uint8)
            | ((ul >= eff_thr).astype(np.uint8) << 1)
            | ((lr >= eff_thr).astype(np.uint8) << 2)
            | ((ur >= eff_thr).astype(np.uint8) << 3)
        )
        disconnect_fg = connect_black

    n_full = int(np.count_nonzero(lut == 15))
    bmask = (lut != 0) & (lut != 15)
    if not np.any(bmask):
        return (n_full, None, disconnect_fg, bmask)

    b_lut = lut[bmask]
    b_ll = ll[bmask]
    b_ul = ul[bmask]
    b_lr = lr[bmask]
    b_ur = ur[bmask]

    m = b_lut.size
    t_low = np.zeros(m, dtype=np.float64)
    t_up = np.zeros(m, dtype=np.float64)
    t_left = np.zeros(m, dtype=np.float64)
    t_right = np.zeros(m, dtype=np.float64)

    bit0 = b_lut & 1
    bit1 = (b_lut >> 1) & 1
    bit2 = (b_lut >> 2) & 1
    bit3 = (b_lut >> 3) & 1

    c_low = bit0 != bit2
    c_up = bit1 != bit3
    c_left = bit0 != bit1
    c_right = bit2 != bit3

    if np.any(c_low):
        t_low[c_low] = (eff_thr - b_ll[c_low]) / (b_lr[c_low] - b_ll[c_low])
    if np.any(c_up):
        t_up[c_up] = (eff_thr - b_ul[c_up]) / (b_ur[c_up] - b_ul[c_up])
    if np.any(c_left):
        t_left[c_left] = (eff_thr - b_ll[c_left]) / (b_ul[c_left] - b_ll[c_left])
    if np.any(c_right):
        t_right[c_right] = (eff_thr - b_lr[c_right]) / (b_ur[c_right] - b_lr[c_right])

    return (n_full, (b_lut, t_low, t_up, t_left, t_right), disconnect_fg, bmask)


def _extract_boundary_segments(bdata, dx, dy, disconnect_fg):
    """Extract primary and saddle segment vectors from marching-squares boundary data."""
    b_lut, t_low, t_up, t_left, t_right = bdata
    m = b_lut.size

    px = np.empty((4, m), dtype=np.float64)
    px[0] = t_low * dx
    px[1] = t_up * dx
    px[2] = 0.0
    px[3] = dx

    py = np.empty((4, m), dtype=np.float64)
    py[0] = 0.0
    py[1] = dy
    py[2] = t_left * dy
    py[3] = t_right * dy

    if disconnect_fg:
        seg1_beg, seg1_end = _SEG1_BEG_DISC, _SEG1_END_DISC
        seg2_beg, seg2_end = _SEG2_BEG_DISC, _SEG2_END_DISC
    else:
        seg1_beg, seg1_end = _SEG1_BEG_CONN, _SEG1_END_CONN
        seg2_beg, seg2_end = _SEG2_BEG_CONN, _SEG2_END_CONN

    idx = np.arange(m, dtype=np.intp)
    seg1_dx = px[seg1_end[b_lut], idx] - px[seg1_beg[b_lut], idx]
    seg1_dy = py[seg1_end[b_lut], idx] - py[seg1_beg[b_lut], idx]

    saddles = np.nonzero((b_lut == 6) | (b_lut == 9))[0]
    if saddles.size > 0:
        s_lut = b_lut[saddles]
        seg2_dx = px[seg2_end[s_lut], saddles] - px[seg2_beg[s_lut], saddles]
        seg2_dy = py[seg2_end[s_lut], saddles] - py[seg2_beg[s_lut], saddles]
    else:
        seg2_dx = seg2_dy = None

    return seg1_dx, seg1_dy, saddles, seg2_dx, seg2_dy


def _marching_squares_imt(
    arr_xy, threshold, dx, dy, is_regular, analyze_black, connect_black, max_s
):
    """Compute (area, perimeter, psi) on an already-prepared (x, y) float64 grid."""
    pix_area = dx * dy
    data = _marching_squares_boundary_data(
        arr_xy, threshold, is_regular, analyze_black, connect_black
    )
    if data is None:
        return 0.0, 0.0, np.zeros(max_s + 1, dtype=np.complex128)

    n_full, bdata, disconnect_fg, _ = data
    if bdata is None:
        return float(n_full) * pix_area, 0.0, np.zeros(max_s + 1, dtype=np.complex128)

    b_lut, t_low, t_up, t_left, t_right = bdata

    # --- Area ---
    w = _AREA_W_DISC if disconnect_fg else _AREA_W_CONN
    a_sw = 0.5 * t_low * t_left
    a_nw = 0.5 * t_up * (1.0 - t_left)
    a_se = 0.5 * (1.0 - t_low) * t_right
    a_ne = 0.5 * (1.0 - t_up) * (1.0 - t_right)
    a_left = 0.5 * (t_low + t_up)
    a_bot = 0.5 * (t_left + t_right)

    boundary_area_cells = (
        np.sum(w[b_lut, 0])
        + np.dot(w[b_lut, 1], a_sw)
        + np.dot(w[b_lut, 2], a_nw)
        + np.dot(w[b_lut, 3], a_se)
        + np.dot(w[b_lut, 4], a_ne)
        + np.dot(w[b_lut, 5], a_left)
        + np.dot(w[b_lut, 6], a_bot)
    )
    area = (float(n_full) + float(boundary_area_cells)) * pix_area

    # --- Contour segments ---
    seg1_dx, seg1_dy, _, seg2_dx, seg2_dy = _extract_boundary_segments(
        bdata, dx, dy, disconnect_fg
    )
    if seg2_dx is not None:
        all_dx = np.concatenate((seg1_dx, seg2_dx))
        all_dy = np.concatenate((seg1_dy, seg2_dy))
    else:
        all_dx = seg1_dx
        all_dy = seg1_dy

    perimeter, psi = _accumulate_segments_psi(all_dx, all_dy, max_s)
    return area, perimeter, psi


def _marching_squares_map_single(
    arr_xy, threshold, dx, dy, s, is_regular, analyze_black, connect_black
):
    """Compute complex128 Minkowski map of order s on prepared (x, y) grid."""
    nx, ny = arr_xy.shape
    out_nx = max(nx - 1, 0)
    out_ny = max(ny - 1, 0)
    mmap = np.zeros((out_nx, out_ny), dtype=np.complex128)
    if out_nx == 0 or out_ny == 0:
        return mmap

    data = _marching_squares_boundary_data(
        arr_xy, threshold, is_regular, analyze_black, connect_black
    )
    if data is None or data[1] is None:
        return mmap

    _, bdata, disconnect_fg, bmask = data
    seg1_dx, seg1_dy, saddles, seg2_dx, seg2_dy = _extract_boundary_segments(
        bdata, dx, dy, disconnect_fg
    )
    cell_vals = _segment_psi_s(seg1_dx, seg1_dy, s)
    if seg2_dx is not None:
        cell_vals[saddles] += _segment_psi_s(seg2_dx, seg2_dy, s)

    mmap[bmask] = cell_vals
    return mmap


